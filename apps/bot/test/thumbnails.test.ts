import { describe, expect, test } from "bun:test";
import { classify, type Head, playlistThumbnail, thumbnailFor, upgrade } from "../src/music/thumbnails";

const yt = { sourceName: "youtube", uri: "https://www.youtube.com/watch?v=abc", author: "Some Channel" };

describe("music vs video (#104, spec #62)", () => {
  const music = { isVideo: false, isAudioOnly: true, isMusicContent: true };
  const video = { isVideo: true, isAudioOnly: false, isMusicContent: false };

  test("Spotify and YouTube Music links are always music", () => {
    expect(classify({ sourceName: "spotify", uri: "https://open.spotify.com/track/x", author: "A" })).toEqual(music);
    expect(classify({ ...yt, uri: "https://music.youtube.com/watch?v=abc" })).toEqual(music);
  });

  test("a YouTube upload is music for category 10, a music topic, a Topic channel or a label credit", () => {
    expect(classify({ ...yt, categoryId: "10" })).toEqual(music);
    expect(classify({ ...yt, topics: ["https://en.wikipedia.org/wiki/Pop_music"] })).toEqual(music);
    expect(classify({ ...yt, author: "LiSA - Topic" })).toEqual(music);
    expect(classify({ ...yt, description: "Provided to YouTube by Sony Music" })).toEqual(music);
    expect(classify({ ...yt, description: "Auto-generated by YouTube." })).toEqual(music);
  });

  test("any other YouTube upload is a video", () => {
    expect(classify(yt)).toEqual(video);
    expect(classify({ ...yt, categoryId: "20", topics: ["https://en.wikipedia.org/wiki/Video_game_culture"] })).toEqual(
      video,
    );
  });

  test("music gets the square-ish sddefault, video the 16:9 mqdefault", () => {
    expect(thumbnailFor("abc", true)).toBe("https://i.ytimg.com/vi/abc/sddefault.jpg");
    expect(thumbnailFor("abc", false)).toBe("https://img.youtube.com/vi/abc/mqdefault.jpg");
  });
});

/** A HEAD that answers per URL: missing URLs fail. */
const heads =
  (answers: Record<string, { ok: boolean; contentType: string; contentLength: number }>): Head =>
  async (url) =>
    answers[url] ?? { ok: false, contentType: "", contentLength: 0 };
const image = { ok: true, contentType: "image/jpeg", contentLength: 50_000 };

describe("thumbnail upgrade (#104, spec #63)", () => {
  const mq = "https://img.youtube.com/vi/abc/mqdefault.jpg";
  const maxres = "https://img.youtube.com/vi/abc/maxresdefault.jpg";
  const hq = "https://img.youtube.com/vi/abc/hqdefault.jpg";

  test("a YouTube video thumbnail becomes maxres when that is a real image", async () => {
    expect(await upgrade(mq, heads({ [maxres]: image }))).toBe(maxres);
  });

  test("maxres missing, not an image, or a tiny placeholder falls back to hq, then the original", async () => {
    expect(await upgrade(mq, heads({ [hq]: image }))).toBe(hq);
    expect(await upgrade(mq, heads({ [maxres]: { ...image, contentType: "text/html" }, [hq]: image }))).toBe(hq);
    expect(await upgrade(mq, heads({ [maxres]: { ...image, contentLength: 800 } }))).toBe(mq);
  });

  test("a music thumbnail (sddefault) keeps its shape", async () => {
    const sd = "https://i.ytimg.com/vi/abc/sddefault.jpg";
    expect(await upgrade(sd, heads({}))).toBe(sd);
  });

  test("a non-YouTube image is kept only if it checks out", async () => {
    const art = "https://i.scdn.co/image/abc";
    expect(await upgrade(art, heads({ [art]: image }))).toBe(art);
    expect(await upgrade(art, heads({}))).toBeNull();
    expect(await upgrade(null, heads({}))).toBeNull();
  });
});

describe("playlist thumbnail (#104, spec #64)", () => {
  test("the playlist's own image first, then the first track's thumbnail", async () => {
    const own = "https://i.scdn.co/image/playlist";
    const first = "https://i.ytimg.com/vi/abc/sddefault.jpg";
    expect(await playlistThumbnail(async () => own, first, heads({ [own]: image }))).toBe(own);
    expect(await playlistThumbnail(async () => null, first, heads({}))).toBe(first);
    expect(await playlistThumbnail(async () => own, null, heads({}))).toBeNull();
  });
});
