import { isInternalUrl } from "./url-safety";

/** What a track is, for choosing its picture (spec #62). */
export interface Classification {
  isVideo: boolean;
  isAudioOnly: boolean;
  isMusicContent: boolean;
}

export interface ClassifyInput {
  sourceName: string;
  uri: string;
  author: string;
  /** YouTube Data API `snippet.categoryId`, when it was looked up. */
  categoryId?: string | null;
  /** YouTube Data API `topicDetails.topicCategories` (Wikipedia URLs). */
  topics?: readonly string[];
  description?: string;
}

const MUSIC = { isVideo: false, isAudioOnly: true, isMusicContent: true } as const;
const VIDEO = { isVideo: true, isAudioOnly: false, isMusicContent: false } as const;
const LABEL_CREDIT = /provided to youtube by|auto-generated by youtube/i;

/**
 * Spec #62: Spotify and YouTube Music are always music. A YouTube upload is music when it is in
 * category 10, has a music topic, comes from a "- Topic" channel or carries a label's credit line.
 */
export function classify(input: ClassifyInput): Classification {
  if (input.sourceName !== "youtube" || input.uri.includes("music.youtube.com")) return MUSIC;
  const music =
    input.categoryId === "10" ||
    (input.topics ?? []).some((t) => /music/i.test(t)) ||
    /- Topic$/.test(input.author.trim()) ||
    LABEL_CREDIT.test(input.description ?? "");
  return music ? MUSIC : VIDEO;
}

/** Spec #62: music gets the square-ish sddefault, video the 16:9 mqdefault. */
export const thumbnailFor = (videoId: string, music: boolean): string =>
  music ? `https://i.ytimg.com/vi/${videoId}/sddefault.jpg` : `https://img.youtube.com/vi/${videoId}/mqdefault.jpg`;

/** A HEAD request's answer; injected so tests and the Bot decide how to fetch. */
export type Head = (url: string) => Promise<{ ok: boolean; contentType: string; contentLength: number }>;

/** A picture worth showing: answered, an image, and more than a placeholder's 1 KB (spec #63). */
async function isImage(url: string, head: Head): Promise<boolean> {
  // The URL comes from track metadata or a scraped page: never ask an internal address (SSRF).
  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    return false;
  }
  if (!/^https?:$/.test(parsed.protocol) || isInternalUrl(parsed)) return false;
  const answer = await head(url).catch(() => null);
  return Boolean(answer?.ok && answer.contentType.startsWith("image/") && answer.contentLength > 1024);
}

const YOUTUBE_THUMB = /^https:\/\/(?:i\.ytimg\.com|img\.youtube\.com)\/vi\/([\w-]+)\/([a-z]+)\.jpg(?:\?.*)?$/;

/** maxresdefault, else hqdefault — both asked at once; null when neither is a real image. */
async function bestOf(url: string, id: string, head: Head): Promise<string | null> {
  const base = url.replace(/\/vi\/[\w-]+\/.*$/, `/vi/${id}`);
  const candidates = [`${base}/maxresdefault.jpg`, `${base}/hqdefault.jpg`];
  const checks = await Promise.all(candidates.map((c) => isImage(c, head)));
  return candidates[checks.indexOf(true)] ?? null;
}

/**
 * Spec #63: a YouTube video thumbnail (mqdefault) becomes maxresdefault when that is a real
 * image, else hqdefault, else stays. A music thumbnail keeps its shape. Any other picture is kept
 * only if it checks out.
 */
export async function upgrade(url: string | null, head: Head): Promise<string | null> {
  if (!url) return null;
  const youtube = YOUTUBE_THUMB.exec(url);
  if (!youtube) return (await isImage(url, head)) ? url : null;
  const [, id, variant] = youtube;
  if (variant !== "mqdefault") return url;
  return (await bestOf(url, id ?? "", head)) ?? url;
}

/** Spec #64: the playlist's own picture (Spotify image, YouTube page image), then the first track's. */
export async function playlistThumbnail(
  own: () => Promise<string | null>,
  firstTrack: string | null,
  head: Head,
): Promise<string | null> {
  const found = await own().catch(() => null);
  // A YouTube page image (any variant, often with a query string) is upgraded to maxres (spec #64).
  const youtube = found ? YOUTUBE_THUMB.exec(found) : null;
  if (found && youtube) return (await bestOf(found, youtube[1] ?? "", head)) ?? found;
  const checked = await upgrade(found, head);
  return checked ?? firstTrack;
}
